import { createInterface } from "node:readline/promises";
import { stdin, stdout } from "node:process";
import { access, chmod, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { resolve } from "node:path";

const root = resolve(new URL("..", import.meta.url).pathname);
const args = new Map();
for (let index = 2; index < process.argv.length; index += 2) {
  const name = process.argv[index];
  if (!name?.startsWith("--") || process.argv[index + 1] === undefined) {
    console.error("Usage: node scripts/configure.mjs [--heater-ip IP] [--gateway-ip IP] [--interface NAME]");
    process.exit(2);
  }
  args.set(name.slice(2), process.argv[index + 1]);
}

const interactive = stdin.isTTY;
const prompt = interactive ? createInterface({ input: stdin, output: stdout }) : null;
async function answer(name, question, fallback) {
  if (args.has(name)) return args.get(name).trim();
  if (!prompt) return fallback;
  return (await prompt.question(`${question} [${fallback}]: `)).trim() || fallback;
}

const heaterIp = await answer("heater-ip", "Heater IPv4 address", "192.168.2.3");
const gatewayIp = await answer("gateway-ip", "Gateway IPv4 address on the heater network", "192.168.2.1");
const networkInterface = await answer("interface", "macOS Internet Sharing interface", "bridge100");
prompt?.close();

function validIp(value) {
  const parts = value.split(".");
  return parts.length === 4 && parts.every((part) => /^\d{1,3}$/.test(part) && Number(part) <= 255);
}
if (!validIp(heaterIp) || !validIp(gatewayIp)) throw new Error("Heater and gateway addresses must be valid IPv4 addresses");
if (!/^[a-zA-Z0-9._-]+$/.test(networkInterface)) throw new Error("Interface name contains unsupported characters");

const env = `# Generated by scripts/configure.mjs\nICOMM_LOCAL_IP=${gatewayIp}\nICOMM_DASHBOARD_PORT=8788\nICOMM_TLS_PORT=8443\nICOMM_DNS_PORT=1053\nICOMM_ANS_PORT=15555\nICOMM_DEVICE_ID=\nICOMM_DEBUG_PACKETS=false\nICOMM_DNS_CAPTURE_ALL=true\n`;
const pf = `# Generated by scripts/configure.mjs. Load only after reviewing.\nheater = "${heaterIp}"\ngateway = "${gatewayIp}"\n\n# Capture the heater's cloud-facing protocols locally.\nrdr pass on ${networkInterface} inet proto udp from $heater to any port 53 -> $gateway port 1053\nrdr pass on ${networkInterface} inet proto udp from $heater to any port 55055 -> $gateway port 15555\nrdr pass on ${networkInterface} inet proto tcp from $heater to any port 443 -> $gateway port 8443\n\n# DHCP must remain available so the heater can retain its address.\npass quick on ${networkInterface} inet proto udp from any port 68 to any port 67 keep state\n\n# Nothing else from this heater may leave the isolated network.\nblock drop quick on ${networkInterface} inet from $heater to any\n`;

for (const [path, contents] of [[resolve(root, ".env"), env], [resolve(root, "pf-local-only.generated.conf"), pf]]) {
  try {
    await access(path, constants.F_OK);
    throw new Error(`${path} already exists; move it aside before regenerating configuration`);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  await writeFile(path, contents, { mode: 0o600 });
  await chmod(path, 0o600);
  console.log(`Created ${path}`);
}

console.log("Review pf-local-only.generated.conf before loading it with pfctl.");
